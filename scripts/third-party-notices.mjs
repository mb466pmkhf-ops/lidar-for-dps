#!/usr/bin/env node
// Builds the third-party notices that ship with the web and desktop apps, and fails when a
// dependency carries a licence that isn't on the allow list (a release gate).
//
//   node scripts/third-party-notices.mjs [--cargo-metadata path/to/metadata.json] [--check]
//
// npm: production dependencies of web/ (needs `npm ci` first).
// Rust: pass the output of `cargo metadata --format-version 1 --locked` from web/src-tauri.
// --check: don't write, only fail if the committed file is out of date or a licence isn't allowed.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const web = join(root, 'web');
const out = join(web, 'public', 'third-party-notices.txt');
const args = process.argv.slice(2);
const check = args.includes('--check');
const metaIdx = args.indexOf('--cargo-metadata');
const cargoMeta = metaIdx >= 0 ? args[metaIdx + 1] : null;

// Licences we can ship in a closed-source app with a notice. Anything else stops the release.
const ALLOWED = new Set(['MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Zlib', 'Unlicense', '0BSD',
  'Unicode-3.0', 'Unicode-DFS-2016', 'MPL-2.0', 'BSL-1.0', 'CC0-1.0', 'OFL-1.1', 'Apache-2.0 WITH LLVM-exception']);

function allowed(expr) {
  if (!expr) return false;
  // "A OR B" is fine if any side is allowed; "A AND B" needs both; "A/B" is the old spelling of OR.
  return expr.replace(/[()]/g, '').split(/\s+OR\s+|\//).some((alt) =>
    alt.split(/\s+AND\s+/).every((id) => ALLOWED.has(id.trim())));
}

function licenceText(dir) {
  if (!existsSync(dir)) return '';
  const f = readdirSync(dir).filter((n) => /^(licen[cs]e|copying|notice)/i.test(n)).sort();
  return f.map((n) => readFileSync(join(dir, n), 'utf8').trim()).join('\n\n');
}

const problems = [];
const blocks = [];

// npm production tree
const tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--json'], { cwd: web, encoding: 'utf8' }));
const npm = new Map();
(function walk(deps) {
  for (const [name, d] of Object.entries(deps ?? {})) {
    const key = `${name}@${d.version}`;
    if (npm.has(key)) continue;
    npm.set(key, name);
    walk(d.dependencies);
  }
})(tree.dependencies);
for (const key of [...npm.keys()].sort()) {
  const name = npm.get(key);
  const dir = join(web, 'node_modules', name);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const lic = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type;
  if (!allowed(lic)) problems.push(`npm ${key}: licence "${lic}" is not on the allow list`);
  blocks.push(`${key} (npm) — ${lic}\n${licenceText(dir) || '(no licence file in the package; licence: ' + lic + ')'}`);
}

// Rust crates of the desktop app
if (cargoMeta) {
  const meta = JSON.parse(readFileSync(cargoMeta, 'utf8'));
  const own = new Set(meta.workspace_members);
  const crates = meta.packages.filter((p) => !own.has(p.id)).sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  for (const p of crates) {
    if (!allowed(p.license)) problems.push(`crate ${p.name}@${p.version}: licence "${p.license}" is not on the allow list`);
    const text = licenceText(dirname(p.manifest_path));
    blocks.push(`${p.name}@${p.version} (Rust crate) — ${p.license}${p.repository ? '\nSource: ' + p.repository : ''}\n${text || '(licence: ' + p.license + ')'}`);
  }
}

// Fonts bundled with every app
blocks.push(`Poppins (font) — OFL-1.1\n${readFileSync(join(root, 'FrameScout/Resources/Fonts/OFL.txt'), 'utf8').trim()}`);

// Many packages ship the same licence text (Apache-2.0, MIT with the same holder…). Print each
// distinct text once with the packages that use it, so the file stays readable and small.
const groups = new Map();
for (const b of blocks) {
  const [title, ...rest] = b.split('\n');
  const src = rest[0]?.startsWith('Source: ') ? rest.shift() : '';
  const body = rest.join('\n');
  if (!groups.has(body)) groups.set(body, []);
  groups.get(body).push(src ? `${title}  ${src.replace('Source: ', '')}` : title);
}
const header = `FrameScout third-party notices
Generated by scripts/third-party-notices.mjs. FrameScout includes the following open-source software.
${cargoMeta ? '' : '(Rust crates of the desktop app are listed when generated with --cargo-metadata.)\n'}`;
const text = header + '\n' + [...groups.entries()].map(([body, names]) =>
  '='.repeat(72) + '\n' + names.join('\n') + '\n\n' + body).join('\n\n') + '\n';

if (problems.length) {
  console.error('Licence check failed:\n  ' + problems.join('\n  '));
  process.exit(1);
}
if (check) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== text) {
    console.error('web/public/third-party-notices.txt is out of date. Run: node scripts/third-party-notices.mjs --cargo-metadata <file>');
    process.exit(1);
  }
  console.log(`Notices up to date (${blocks.length} entries), all licences allowed.`);
} else {
  writeFileSync(out, text);
  console.log(`Wrote ${out} (${blocks.length} entries).`);
}
